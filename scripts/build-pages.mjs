import {mkdir, readFile, writeFile, copyFile} from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const target = new URL('docs/', root);
await mkdir(new URL('static/', target), {recursive:true});
for (const file of ['app.js','style.css','scanner.js']) await copyFile(new URL(`app/static/${file}`,root),new URL(`static/${file}`,target));
await copyFile(new URL('netlify/browser/storage.js',root),new URL('static/storage.js',target));
await copyFile(new URL('pages/analyze.js',root),new URL('static/analyze.js',target));
let html = await readFile(new URL('app/static/index.html',root),'utf8');
html = html.replace('<script src="/static/app.js"></script>','<script src="./static/analyze.js"></script><script src="./static/storage.js"></script><script src="./static/app.js"></script>');
html = html.replaceAll('src="/static/', 'src="./static/');
html = html.replaceAll('href="/"','href="./"').replaceAll('href="/static/','href="./static/');
html = html.replace('LOCAL · PROTOTYPE','GITHUB PAGES · DEMO');
html = html.replace('로컬 저장 · 외부 AI 전송 없음','브라우저에서 분석·저장 · 서버 전송 없음');
html = html.replace('<form id="analysis-form">','<div class="hosting-note" role="note">GitHub Pages 시연 버전 · 샘플 또는 직접 입력한 상품 설명을 이 브라우저에서 비교합니다. URL 자동 수집과 이미지 비교는 지원하지 않습니다. 기록은 현재 브라우저에 저장되며 서버로 전송되지 않습니다.</div><form id="analysis-form">');
html = html.replace('공개된 상품 페이지에서 제목·설명·이미지를 확인합니다.','출처 기록용 URL입니다. 상품명과 설명은 아래에 직접 입력해 주세요.');
html = html.replace('<details id="manual-details">','<details id="manual-details" open>');
html = html.replace('페이지 수집이 어렵다면 직접 입력하기','비교할 상품명·설명 입력');
html = html.replace('상품명과 설명을 붙여넣어 주세요. 입력 시 URL 수집 대신 이 내용을 분석합니다.','확인할 상품명과 설명을 붙여넣어 주세요. 이 내용과 권리 자료를 비교합니다.');
html = html.replace('로그인이나 동적 로딩이 필요한 페이지는 자동으로 수집되지 않을 수 있습니다.','이 버전은 외부 사이트에 접속하지 않습니다. 상품 페이지의 설명을 복사해 위에 입력해 주세요.');
html = html.replace('원본 이미지 <em>선택 · 파일 동일성 검사</em>','원본 이미지 <em>선택 · 파일명 기록용</em>');
html = html.replace('동일 파일을 확인합니다. 시각적 유사도 분석은 지원 예정입니다.','이 정적 데모에서는 이미지 비교를 수행하지 않습니다.');
html = html.replace('원본 상품 설명이나 확인할 문구를 입력하세요.','원본 상품 설명이나 확인할 문구를 입력하세요.');
await writeFile(new URL('index.html',target),html);
await writeFile(new URL('.nojekyll',target),'');
console.log('Built docs/: standalone GitHub Pages demo, no dependencies or backend required.');
